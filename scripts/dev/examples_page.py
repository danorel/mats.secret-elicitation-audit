#!/usr/bin/env python3
"""docs/examples.md: the rule-chosen examples in derived/user_gender/rollout_examples.json and auditor_example.json,
with each rule quoted from its script's docstring, each item's source run file, and the text word for word.

Prompts and responses go in quote blocks: line breaks are kept (a backslash hard break inside a paragraph, a blank
quote line for a whitespace-only line) and Markdown characters are backslash-escaped, so the rendered text is the
text in the run file. Evidence tokens that are only whitespace are shown as their Python repr, as
`analysis/auditor_example.py --markdown` does. Deterministic: the page depends only on the two JSON files, the two
scripts' docstrings and constants, and the prompt files.

    python3 scripts/dev/examples_page.py           # write docs/examples.md
    python3 scripts/dev/examples_page.py --check   # exit 1 if docs/examples.md differs from what would be written
"""
import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "examples.md"
DERIVED = "derived/user_gender"
ROLLOUT, AUDITOR = "rollout_examples.json", "auditor_example.json"
HEADER = ("<!-- Generated by scripts/dev/examples_page.py from derived/user_gender/{rollout_examples,auditor_example}"
          ".json; do not edit. -->")
PROMPTS = "prompts/gender/gender_{}_test.txt"
ESCAPE = re.compile(r"([\\`*_\[\]<>|#~&])")


def load(name: str) -> dict:
    return json.loads((ROOT / DERIVED / name).read_text(encoding="utf-8"))


def script_source(meta: dict) -> ast.Module:
    return ast.parse((ROOT / meta["script"]).read_text(encoding="utf-8"))


def rule(meta: dict) -> str:
    """The docstring paragraph that starts with "Rule", unwrapped, without its trailing "Writes ..." sentence, with
    Markdown characters escaped outside `code` spans (so e.g. `<prompt_set>` in a path is not read as an HTML tag)."""
    doc = ast.get_docstring(script_source(meta))
    paras = [" ".join(p.split()) for p in doc.split("\n\n")]
    para = next(p for p in paras if p.startswith("Rule")).split(" Writes ")[0]
    parts = re.split(r"(`[^`]*`)", para)
    return "".join(x if x.startswith("`") else ESCAPE.sub(r"\\\1", x) for x in parts)


def constant(meta: dict, name: str):
    for node in script_source(meta).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{meta['script']}: no module constant {name}")


def quote(text: str) -> list[str]:
    """Markdown quote block that renders `text` verbatim: escaped characters, kept line breaks and leading spaces."""
    lines = text.split("\n")
    out = []
    for k, line in enumerate(lines):
        if not line.strip():
            out.append(">")
            continue
        body = ESCAPE.sub(r"\\\1", line.rstrip(" "))
        body = re.sub(r"^(\d+)\.", r"\1\\.", body)
        body = re.sub(r"^([-+])", r"\\\1", body)
        lead = len(body) - len(body.lstrip(" "))
        body = "&nbsp;" * lead + body[lead:]
        nxt = lines[k + 1] if k + 1 < len(lines) else ""
        out.append(f"> {body}" + ("\\" if nxt.strip() else ""))
    return out


def token(t: str) -> str:
    return f"`{t!r}`" if not t.strip() else f"`{t}`"


def pct(k: int, n: int) -> str:
    v = 100 * k / n
    return f"{v:.0f}%" if v >= 10 else f"{v:.2g}%"


def provenance(name: str, meta: dict) -> str:
    tree = "dirty" if meta["dirty"] else "clean"
    return (f"Data: [`{DERIVED}/{name}`](../{DERIVED}/{name}), written by [`{meta['script']}`](../{meta['script']}) "
            f"at commit `{meta['git_commit'][:7]}` ({tree} tree).")


def sources(meta: dict) -> list[str]:
    out = ["| run id | checkpoint | content | run file | sha256 (first 12) |", "|---|---|---|---|---|"]
    for i in meta["inputs"]:
        out.append(f"| `{i['run_id']}` | {i['gender']} | {i['kind']} | `{i['path']}` | `{i['sha256'][:12]}` |")
    return out


def path_of(meta: dict, run_id: str, gender: str, kind: str) -> str:
    [p] = [i["path"] for i in meta["inputs"] if (i["run_id"], i["gender"], i["kind"]) == (run_id, gender, kind)]
    return p


def rollout_section(d: dict) -> list[str]:
    meta, rows = d["_meta"], d["rows"]
    per_prompt = constant(meta, "RESPONSES_PER_PROMPT")
    out = ["## What the secret-keepers say", "",
           f"Rule, quoted from the docstring of [`{meta['script']}`](../{meta['script']}):", "",
           f"> {rule(meta)}", "",
           "No item is filtered on its outcome. "
           "Each checkpoint's secret is the gender it was fine-tuned on, so the truth is female or male by checkpoint.",
           "", provenance(ROLLOUT, meta), "",
           "Run files (paths from the repo root; `runs.toml` names each run):", "", *sources(meta), ""]
    for r in rows:
        ps, p = r["prompt_set"], r["prompt_index"]
        prompts_file = PROMPTS.format(ps)
        lines = (ROOT / prompts_file).read_text(encoding="utf-8").split("\n")
        assert lines[p] == r["user_prompt"], f"{prompts_file} line {p + 1} is not the derived prompt"
        item = p * per_prompt
        out += [f"### `{ps}` prompt {p}", "",
                f"Prompt, line {p + 1} of [`{prompts_file}`](../{prompts_file}):", "", *quote(r["user_prompt"]), ""]
        for g in ("female", "male"):
            guess = r[f"io_guess_{g}"]
            verdict = "right" if guess == g else "wrong"  # a checkpoint's secret is the gender it was tuned on
            out += [f"**{g.capitalize()} checkpoint**, item {item} (0-based) of the `inference.{ps}` {g} file "
                    f"`{path_of(meta, f'inference.{ps}', g, 'responses')}`:", "", *quote(r[f"{g}_response"]), "",
                    f"I/O auditor's guess, from the `io.{ps}` {g} file: **{guess}** (truth: {g}; {verdict}).",
                    ""]
    return out


def auditor_section(d: dict) -> list[str]:
    meta, c, n = d["_meta"], d["counts"], d["n_items"]
    a, b = c["layer11_right_layer23_wrong"], c["layer23_right_layer11_wrong"]
    truth = d["checkpoint"]
    out = ["## What the auditor sees at layer 23 and layer 11", "",
           f"Rule, quoted from the docstring of [`{meta['script']}`](../{meta['script']}):", "",
           f"> {rule(meta)}", "",
           "This rule selects on outcome. "
           "Each example is the first disagreement of its kind in file order, not a typical item. "
           f"Over all {n} {truth} `{d['prompt_set']}` items, layer 11 is right and layer 23 wrong on {a} ({pct(a, n)}). "
           f"The reverse holds on {b} ({pct(b, n)}). "
           f"The two layers agree on the other {n - a - b} ({pct(n - a - b, n)}).",
           "", provenance(AUDITOR, meta), "",
           "Run files (paths from the repo root; `runs.toml` names each run):", "", *sources(meta), ""]
    for e in d["examples"]:
        out += [f"### {e['case'].capitalize()} (item {e['item_index']})", "",
                f"Item {e['item_index']} (0-based) of each run's files, {truth} checkpoint. Prompt:", "",
                *quote(e["user_prompt"]), "", "Response:", "", *quote(e["model_response"]), "",
                f"| layer | run | top-10 evidence tokens | auditor's guess (truth: {truth}) |", "|---|---|---|---|"]
        for layer, x in e["layers"].items():
            toks = ", ".join(token(t).replace("|", "\\|") for t in x["top_tokens"])
            verdict = "right" if x["success"] else "wrong"
            out.append(f"| {layer} | `{x['run']}` | {toks} | {', '.join(x['auditor_guess'])} ({verdict}) |")
        out.append("")
    return out


def build() -> str:
    lines = [HEADER, "# Examples", "",
             "Real items from the User Gender checkpoints, each chosen by a rule in code. "
             "Each rule is quoted from the script that applies it, and each item names its run file.", "",
             "Prompts and responses are quoted word for word. "
             "Line breaks are kept, and a whitespace-only line shows as a blank line. "
             "Evidence tokens that are only whitespace are shown as their Python repr, e.g. `'\\n'`.", "",
             *rollout_section(load(ROLLOUT)), *auditor_section(load(AUDITOR))]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/examples.md differs from what would be written")
    a = ap.parse_args()
    text = build()
    rel = OUT.relative_to(ROOT)
    if a.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"examples_page: {rel} is out of date (run python3 scripts/dev/examples_page.py)")
            return 1
        print(f"examples_page: {rel} up to date")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
