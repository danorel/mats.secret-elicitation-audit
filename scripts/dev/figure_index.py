#!/usr/bin/env python3
"""figures/readme/README.md and figures/writeup/README.md: one table row per PNG in figures/readme/ (the write-up
folder mirrors it; scripts/dev/check_refs.py enforces that).

Order: where the figure is first referenced in README.md, then EXPERIMENTS.md; unreferenced figures last, by name.
Caption: the first sentence of the italic paragraph (`*...*`, possibly hard-wrapped) right after the figure's image
line in README.md, else in EXPERIMENTS.md; "(no caption)" when neither has one. Alt text and link text are never used.
Status: the figure's cells in plots/status.csv, summarised as post hoc and not-claimed counts.

    python3 scripts/dev/figure_index.py           # write both indexes
    python3 scripts/dev/figure_index.py --check   # exit 1 if either file on disk differs from what would be written
"""
import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ["README.md", "EXPERIMENTS.md"]
LINKED, MIRROR = "figures/readme", "figures/writeup"
STATUS = "plots/status.csv"
HEADER = "<!-- Generated by scripts/dev/figure_index.py; do not edit. -->"
NO_CAPTION = "(no caption)"
TIMINGS = {"fixed_in_advance", "post_hoc"}
CLAIMS = {"claimed", "not claimed"}
# A sentence ends at . ! or ? followed by whitespace and something that can start a sentence.
SENTENCE_END = re.compile(r"[.!?](?=\s+[A-Z0-9`(*\"“])")
ABBREVIATIONS = ("e.g", "i.e", "vs", "cf", "etc", "approx")


def first_sentence(text: str) -> str:
    for m in SENTENCE_END.finditer(text):
        if not text[: m.start()].lower().endswith(ABBREVIATIONS):
            return text[: m.end()]
    return text


def caption_in(doc: str, name: str) -> str | None:
    """The italic paragraph after the first image line of `name` in `doc` that has one, unwrapped and unstarred."""
    lines = doc.splitlines()
    image = re.compile(r"!\[[^\]]*\]\(" + re.escape(f"{LINKED}/{name}") + r"\)")
    for i, line in enumerate(lines):
        if not image.search(line):
            continue
        j = i + 1
        while j < len(lines) and not lines[j].strip():
            j += 1
        para = []
        while j < len(lines) and lines[j].strip():
            para.append(lines[j].strip())
            j += 1
        text = " ".join(para)
        if text.startswith("*") and not text.startswith("**") and text.endswith("*") and not text.endswith("**"):
            return text[1:-1].strip()
    return None


def caption(docs: dict[str, str], name: str) -> str:
    for doc in docs.values():
        if (c := caption_in(doc, name)) is not None:
            return first_sentence(c).replace("|", "\\|")
    return NO_CAPTION


def order(docs: dict[str, str], names: list[str]) -> list[str]:
    def first_ref(name: str):
        for k, doc in enumerate(docs.values()):
            if (pos := doc.find(f"{LINKED}/{name}")) >= 0:
                return (k, pos, name)
        return (len(docs), 0, name)
    return sorted(names, key=first_ref)


def statuses() -> dict[str, str]:
    cells: dict[str, list[dict]] = {}
    with (ROOT / STATUS).open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["timing"] not in TIMINGS or row["claim"] not in CLAIMS:
                raise ValueError(f"{STATUS}: unexpected timing/claim in {row}")
            cells.setdefault(row["figure"], []).append(row)
    out = {}
    for fig, rows in cells.items():
        n = len(rows)
        post = sum(r["timing"] == "post_hoc" for r in rows)
        unclaimed = sum(r["claim"] == "not claimed" for r in rows)
        post_s = "none post hoc" if post == 0 else "all post hoc" if post == n else f"{post} post hoc"
        claim_s = "all claimed" if unclaimed == 0 else "none claimed" if unclaimed == n else f"{unclaimed} not claimed"
        out[fig] = f"{n} cell{'s' if n != 1 else ''} · {post_s} · {claim_s}"
    return out


def render(intro: list[str], rows: list[tuple[str, str, str]]) -> str:
    out = [HEADER, *intro, "", "| # | figure | caption (first sentence) | status |", "|---|---|---|---|"]
    for k, (name, cap, status) in enumerate(rows, 1):
        stem = Path(name).stem
        thumb = f'<a href="{name}"><img src="{name}" width="240" alt="{stem}"></a>'
        out.append(f"| {k:02d} | {thumb} | {cap} | {status} |")
    return "\n".join(out) + "\n"


def build() -> dict[Path, str]:
    docs = {d: (ROOT / d).read_text(encoding="utf-8") for d in DOCS}
    names = order(docs, sorted(p.name for p in (ROOT / LINKED).glob("*.png")))
    status = statuses()
    rows = [(n, caption(docs, n), status.get(Path(n).stem, f"not in {STATUS}")) for n in names]
    common = (f"Statuses: [{STATUS}](../../{STATUS}) (post hoc: the cell's choice was made after seeing data; its `reason` column says which). "
              "Order: first reference in README.md, then EXPERIMENTS.md. Caption: the first sentence of the italic "
              f"paragraph under the figure in README.md, else EXPERIMENTS.md, or {NO_CAPTION}.")
    readme = ["# Figures for README.md and EXPERIMENTS.md", "",
              "Drawn by `make figures` from `derived/user_gender/` (chart scripts in [plots/](../../plots/), "
              "styles-plot's readme target). " + common]
    writeup = ["# Figures for the write-up", "",
               "These are the post-target copies of [figures/readme/](../readme/), for the write-up, which links "
               "them from outside the repo. The same `make figures` run draws both folders from `derived/user_gender/`. "
               + common]
    return {ROOT / LINKED / "README.md": render(readme, rows), ROOT / MIRROR / "README.md": render(writeup, rows)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a file on disk differs from what would be written")
    a = ap.parse_args()
    stale = []
    for path, text in build().items():
        rel = path.relative_to(ROOT)
        if a.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(rel))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("figure_index: out of date (run python3 scripts/dev/figure_index.py): " + ", ".join(stale))
        return 1
    if a.check:
        print("figure_index: both indexes up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
